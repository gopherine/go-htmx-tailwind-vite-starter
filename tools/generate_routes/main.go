package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type page struct {
	Route      string
	ImportPath string
	Alias      string
	FuncName   string
}

func main() {
	startDir, err := os.Getwd()
	if err != nil {
		die(err)
	}

	moduleRoot, err := findModuleRoot(startDir)
	if err != nil {
		die(err)
	}

	modulePath, err := readModulePath(filepath.Join(moduleRoot, "go.mod"))
	if err != nil {
		die(err)
	}

	pages, err := discoverPages(filepath.Join(moduleRoot, "views/pages"), moduleRoot, modulePath)
	if err != nil {
		die(err)
	}

	if err := writeRoutes(filepath.Join(moduleRoot, "internal/routes/routes_gen.go"), pages); err != nil {
		die(err)
	}
}

func readModulePath(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "module ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "module ")), nil
		}
	}
	return "", fmt.Errorf("module path not found in %s", path)
}

func findModuleRoot(start string) (string, error) {
	dir := start
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found starting from %s", start)
		}
		dir = parent
	}
}

func discoverPages(root, moduleRoot, modulePath string) ([]page, error) {
	var pages []page
	aliases := map[string]int{}

	walkFn := func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if strings.HasPrefix(d.Name(), "_") || strings.HasPrefix(d.Name(), ".") {
				return fs.SkipDir
			}
			return nil
		}
		if d.Name() != "index.templ" {
			return nil
		}

		relDir, err := filepath.Rel(root, filepath.Dir(path))
		if err != nil {
			return err
		}
		if relDir != "." && relDir != "" {
			for _, part := range strings.Split(filepath.ToSlash(relDir), "/") {
				if strings.HasPrefix(part, "_") || strings.HasPrefix(part, ".") {
					return nil
				}
			}
		}

		route := routeFromDir(relDir)
		pkg, err := parsePackage(path)
		if err != nil {
			return err
		}
		importRoot := root
		if relDir != "." && relDir != "" {
			importRoot = filepath.Join(root, relDir)
		}
		relImport, err := filepath.Rel(moduleRoot, importRoot)
		if err != nil {
			return err
		}
		importPath := modulePath + "/" + filepath.ToSlash(relImport)
		relToPages, err := filepath.Rel(root, importRoot)
		if err != nil {
			return err
		}
		aliasBase := pkg
		if relToPages != "." && relToPages != "" {
			aliasBase = pkg + "_" + sanitizeAlias(relToPages)
		}
		alias := uniqueAlias(aliasBase, aliases)

		pages = append(pages, page{
			Route:      route,
			ImportPath: importPath,
			Alias:      alias,
			FuncName:   "Page",
		})

		return nil
	}

	if err := filepath.WalkDir(root, walkFn); err != nil {
		return nil, err
	}

	sort.Slice(pages, func(i, j int) bool {
		return pages[i].Route < pages[j].Route
	})

	return pages, nil
}

func parsePackage(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "package ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "package ")), nil
		}
	}
	return "", fmt.Errorf("package not found in %s", path)
}

func routeFromDir(relDir string) string {
	if relDir == "." || relDir == "" {
		return "/"
	}
	parts := strings.Split(filepath.ToSlash(relDir), "/")
	for i, part := range parts {
		if strings.HasPrefix(part, "[...") && strings.HasSuffix(part, "]") {
			parts[i] = "*"
			continue
		}
		if strings.HasPrefix(part, "[") && strings.HasSuffix(part, "]") {
			parts[i] = ":" + strings.TrimSuffix(strings.TrimPrefix(part, "["), "]")
		}
	}
	return "/" + strings.Join(parts, "/")
}

func uniqueAlias(base string, aliases map[string]int) string {
	if _, ok := aliases[base]; !ok {
		aliases[base] = 1
		return base
	}
	aliases[base]++
	return fmt.Sprintf("%s_%d", base, aliases[base])
}

func sanitizeAlias(path string) string {
	return strings.NewReplacer("/", "_", "-", "_", ".", "_").Replace(path)
}

func writeRoutes(path string, pages []page) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/generate_routes; DO NOT EDIT.\n")
	buf.WriteString("package routes\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"net/http\"\n")
	buf.WriteString("\t\"github.com/golang_starter/internal/web\"\n")
	buf.WriteString("\t\"github.com/labstack/echo/v4\"\n")
	for _, page := range pages {
		if page.Alias != "" {
			buf.WriteString(fmt.Sprintf("\t%s \"%s\"\n", page.Alias, page.ImportPath))
		} else {
			buf.WriteString(fmt.Sprintf("\t\"%s\"\n", page.ImportPath))
		}
	}
	buf.WriteString(")\n\n")
	buf.WriteString("func Register(e *echo.Echo) {\n")
	for _, page := range pages {
		buf.WriteString(fmt.Sprintf("\te.GET(\"%s\", handlers.Make(func(c echo.Context) error {\n", page.Route))
		buf.WriteString(fmt.Sprintf("\t\treturn handlers.RenderPage(c, http.StatusOK, %s.%s())\n", page.Alias, page.FuncName))
		buf.WriteString("\t}))\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func die(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
