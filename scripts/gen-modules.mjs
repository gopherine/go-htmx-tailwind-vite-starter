import { promises as fs } from "fs";
import path from "path";

const modulesDir = path.resolve("views/scripts/modules");
const registryPath = path.resolve("views/scripts/modules/registry.ts");

export async function generateModuleRegistry() {
  const entries = await fs.readdir(modulesDir, { withFileTypes: true });
  const modules = entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => name.endsWith(".ts"))
    .filter((name) => name !== "registry.ts" && !name.endsWith(".d.ts"))
    .map((name) => path.basename(name, ".ts"))
    .sort();

  const lines = [];
  lines.push("// Code generated by scripts/gen-modules.mjs; DO NOT EDIT.");
  lines.push("");
  lines.push("export const moduleLoaders = {");
  for (const mod of modules) {
    lines.push(`  "${mod}": () => import("./${mod}"),`);
  }
  lines.push("} as const;");
  lines.push("");
  lines.push("export type ModuleName = keyof typeof moduleLoaders;");
  lines.push("");

  await fs.mkdir(path.dirname(registryPath), { recursive: true });
  await fs.writeFile(registryPath, lines.join("\n"), "utf8");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  generateModuleRegistry().catch((err) => {
    console.error("Failed to generate module registry:", err);
    process.exit(1);
  });
}
